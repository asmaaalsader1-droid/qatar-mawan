import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

export async function POST(request: NextRequest) {
  const supabase = createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return NextResponse.json({ error: "غير مصرح" }, { status: 401 });

  const body = await request.json().catch(() => null);
  if (!body) return NextResponse.json({ error: "بيانات غير صالحة" }, { status: 400 });

  const { workerId } = body as { workerId: string };
  // Favorites stored client-side for guests; for logged-in users we could persist.
  // This endpoint is a placeholder that returns ok.
  return NextResponse.json({ ok: true, workerId });
}
